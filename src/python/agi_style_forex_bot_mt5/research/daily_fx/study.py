"""Predeclared daily FX portfolio study: development first, holdout once.

The plan (hypotheses, variants, periods, costs, controls and acceptance
thresholds) is frozen as canonical JSON and hashed before any result exists.
Development evaluates every configuration of every hypothesis; all of them
count as trials for the deflated Sharpe ratio, the probability of backtest
overfitting and the superior-predictive-ability test. Only hypotheses whose
predeclared primary configuration passes every development gate are evaluated
on the holdout, exactly once: the runner refuses to overwrite a holdout result.
Research only: nothing here builds, checks or sends an order.
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from hashlib import sha256
import json
from pathlib import Path
from typing import Any, Mapping, Sequence

import numpy as np
import pandas as pd

from ..edge_statistics import (deflated_sharpe_ratio, holm_adjusted, moments, probabilistic_sharpe_ratio,
    probability_of_backtest_overfitting, sharpe_ratio, superior_predictive_ability)
from .data import PricePanel
from .portfolio import CostModel, PortfolioConfig, backtest, performance

STUDY_VERSION = "daily_fx_study_v1"


@dataclass(frozen=True)
class Hypothesis:
    hypothesis_id: str
    description: str
    primary: PortfolioConfig
    variants: tuple[PortfolioConfig, ...] = ()

    def configs(self) -> tuple[PortfolioConfig, ...]:
        return (self.primary, *self.variants)

    def to_dict(self) -> dict[str, Any]:
        return {"hypothesis_id": self.hypothesis_id, "description": self.description,
                "primary": self.primary.to_dict(), "variants": [config.to_dict() for config in self.variants]}


@dataclass(frozen=True)
class Acceptance:
    min_development_sharpe: float = 0.3
    min_development_dsr: float = 0.90
    max_development_pbo: float = 0.5
    max_spa_p_value: float = 0.10
    max_random_quota: float = 0.05
    min_stressed_sharpe: float = 0.0
    min_holdout_sharpe: float = 0.0
    min_holdout_psr: float = 0.90
    max_holdout_drawdown: float = 0.30

    def to_dict(self) -> dict[str, float]:
        return dict(self.__dict__)


@dataclass(frozen=True)
class StudyPlan:
    name: str
    currencies: tuple[str, ...]
    development: tuple[str, str]
    holdout: tuple[str, str]
    hypotheses: tuple[Hypothesis, ...]
    costs: CostModel
    cost_stress_factor: float = 2.0
    random_replicas: int = 200
    pbo_blocks: int = 16
    spa_bootstraps: int = 2000
    acceptance: Acceptance = field(default_factory=Acceptance)
    notes: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, Any]:
        return {"study_version": STUDY_VERSION, "name": self.name, "currencies": list(self.currencies),
                "development": list(self.development), "holdout": list(self.holdout),
                "hypotheses": [item.to_dict() for item in self.hypotheses],
                "costs": {"one_way_bps": dict(sorted(self.costs.one_way_bps.items())),
                          "financing_bps_per_year": self.costs.financing_bps_per_year},
                "cost_stress_factor": self.cost_stress_factor, "random_replicas": self.random_replicas,
                "pbo_blocks": self.pbo_blocks, "spa_bootstraps": self.spa_bootstraps,
                "acceptance": self.acceptance.to_dict(), "notes": list(self.notes)}

    def canonical_json(self) -> str:
        return json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":"))

    def plan_hash(self) -> str:
        return sha256(self.canonical_json().encode("utf-8")).hexdigest()

    def validate(self) -> None:
        if not self.hypotheses or len({item.hypothesis_id for item in self.hypotheses}) != len(self.hypotheses):
            raise ValueError("hypotheses must be non-empty with unique ids")
        if pd.Timestamp(self.development[1]) >= pd.Timestamp(self.holdout[0]):
            raise ValueError("the holdout must start after development ends")
        for hypothesis in self.hypotheses:
            for config in hypothesis.configs():
                config.validate()
                if config.signal == "random" or config.flip:
                    raise ValueError("controls are generated by the study, not declared as hypotheses")


def _window(series: pd.Series, period: tuple[str, str]) -> pd.Series:
    start, end = (pd.Timestamp(value, tz="UTC") for value in period)
    return series.loc[start:end]


def _per_period_sharpe(values: pd.Series) -> float:
    try:
        return sharpe_ratio(values.to_numpy())
    except ValueError:
        return 0.0


def _run(panel: PricePanel, config: PortfolioConfig, costs: CostModel, period: tuple[str, str]) -> pd.Series:
    # The full history feeds the look-backs; only returns inside the period are scored.
    return _window(backtest(panel.prices, config, costs).net_returns, period)


def run_development(plan: StudyPlan, panel: PricePanel) -> dict[str, Any]:
    """Evaluate every predeclared configuration on the development period."""

    plan.validate()
    trial_returns: dict[str, pd.Series] = {}
    for hypothesis in plan.hypotheses:
        for index, config in enumerate(hypothesis.configs()):
            trial_returns[f"{hypothesis.hypothesis_id}:{index}"] = _run(panel, config, plan.costs, plan.development)
    matrix = pd.DataFrame(trial_returns).dropna()
    trial_sharpes = [_per_period_sharpe(matrix[column]) for column in matrix.columns]
    pbo = probability_of_backtest_overfitting(matrix.to_numpy(), blocks=plan.pbo_blocks)
    spa = superior_predictive_ability(matrix.to_numpy(), bootstraps=plan.spa_bootstraps)
    results, p_values = [], []
    for hypothesis in plan.hypotheses:
        primary = matrix[f"{hypothesis.hypothesis_id}:0"]
        dsr = deflated_sharpe_ratio(primary.to_numpy(), trial_sharpes)
        random_sharpes = np.array([_per_period_sharpe(_run(panel, replace(hypothesis.primary, signal="random", seed=seed),
                                                           plan.costs, plan.development))
                                   for seed in range(plan.random_replicas)])
        quota = float((np.sum(random_sharpes >= dsr.sharpe) + 1) / (plan.random_replicas + 1))
        flipped = _run(panel, replace(hypothesis.primary, flip=True), plan.costs, plan.development)
        stressed = _run(panel, hypothesis.primary, plan.costs.scaled(plan.cost_stress_factor), plan.development)
        stats = performance(primary)
        skew, kurtosis = moments(primary.to_numpy())
        psr_zero = probabilistic_sharpe_ratio(dsr.sharpe, 0.0, len(primary), skew, kurtosis)
        p_values.append(1.0 - psr_zero)
        variants = {key: performance(matrix[key]) for key in matrix.columns
                    if key.startswith(f"{hypothesis.hypothesis_id}:") and key != f"{hypothesis.hypothesis_id}:0"}
        results.append({
            "hypothesis_id": hypothesis.hypothesis_id,
            "primary": stats,
            "yearly_returns": {str(year): float(value) for year, value in primary.groupby(primary.index.year).sum().items()},
            "psr_vs_zero": psr_zero,
            "deflated_sharpe": dsr.to_dict(),
            "random_control": {"replicas": plan.random_replicas, "median_sharpe": float(np.median(random_sharpes)),
                               "quota": quota},
            "flipped_sharpe": performance(flipped)["sharpe"],
            "cost_stress": {"factor": plan.cost_stress_factor, "sharpe": performance(stressed)["sharpe"]},
            "variants": variants,
            "variant_sharpe_range": [min((item["sharpe"] for item in variants.values()), default=stats["sharpe"]),
                                     max((item["sharpe"] for item in variants.values()), default=stats["sharpe"])],
        })
    adjusted = holm_adjusted(p_values)
    acceptance = plan.acceptance
    for result, holm_p in zip(results, adjusted):
        result["holm_adjusted_p"] = holm_p
        checks = {
            "development_sharpe": result["primary"]["sharpe"] >= acceptance.min_development_sharpe,
            "deflated_sharpe": result["deflated_sharpe"]["deflated_sharpe_ratio"] >= acceptance.min_development_dsr,
            "probability_of_backtest_overfitting": pbo.pbo <= acceptance.max_development_pbo,
            "superior_predictive_ability": spa.p_value <= acceptance.max_spa_p_value,
            "beats_random_signals": result["random_control"]["quota"] <= acceptance.max_random_quota,
            "survives_double_costs": result["cost_stress"]["sharpe"] >= acceptance.min_stressed_sharpe,
        }
        result["checks"] = checks
        result["proceed_to_holdout"] = all(checks.values())
    return {"study_version": STUDY_VERSION, "phase": "development", "plan_hash": plan.plan_hash(),
            "data": {"source": panel.source, "sha256": panel.source_sha256,
                     "first_day": str(matrix.index.min().date()), "last_day": str(matrix.index.max().date()),
                     "days": int(len(matrix))},
            "trials": len(trial_sharpes), "pbo": pbo.to_dict(), "spa": spa.to_dict(), "hypotheses": results,
            "execution_authorized": False}


def run_holdout(plan: StudyPlan, panel: PricePanel, development: Mapping[str, Any],
                output: str | Path) -> dict[str, Any]:
    """Score the holdout once for hypotheses that passed development."""

    plan.validate()
    target = Path(output)
    if target.exists():
        raise FileExistsError("the holdout was already evaluated; it is scored exactly once")
    if development.get("plan_hash") != plan.plan_hash() or development.get("phase") != "development":
        raise ValueError("development results do not belong to this plan")
    acceptance = plan.acceptance
    results = []
    for item in development["hypotheses"]:
        hypothesis = next(entry for entry in plan.hypotheses if entry.hypothesis_id == item["hypothesis_id"])
        if not item["proceed_to_holdout"]:
            results.append({"hypothesis_id": hypothesis.hypothesis_id, "evaluated": False,
                            "reason": "failed development gates"})
            continue
        returns = _run(panel, hypothesis.primary, plan.costs, plan.holdout)
        stats = performance(returns)
        skew, kurtosis = moments(returns.to_numpy())
        psr = probabilistic_sharpe_ratio(sharpe_ratio(returns.to_numpy()), 0.0, len(returns), skew, kurtosis)
        checks = {"holdout_sharpe": stats["sharpe"] >= acceptance.min_holdout_sharpe,
                  "holdout_psr": psr >= acceptance.min_holdout_psr,
                  "holdout_drawdown": stats["max_drawdown"] <= acceptance.max_holdout_drawdown}
        results.append({"hypothesis_id": hypothesis.hypothesis_id, "evaluated": True, "holdout": stats,
                        "psr_vs_zero": psr, "checks": checks, "passed": all(checks.values()),
                        "yearly_returns": {str(year): float(value)
                                           for year, value in returns.groupby(returns.index.year).sum().items()}})
    summary = {"study_version": STUDY_VERSION, "phase": "holdout", "plan_hash": plan.plan_hash(),
               "data": {"source": panel.source, "sha256": panel.source_sha256}, "hypotheses": results,
               "execution_authorized": False}
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("x", encoding="utf-8") as handle:
        json.dump(summary, handle, indent=2, sort_keys=True, default=float)
    return summary


def hypotheses_from_grid(hypothesis_id: str, description: str, primary: PortfolioConfig,
                         grid: Mapping[str, Sequence[Any]]) -> Hypothesis:
    """Primary configuration plus every single-parameter variation in ``grid``."""

    variants = []
    for key, values in grid.items():
        for value in values:
            value = tuple(int(item) for item in value) if key == "lookbacks" else value
            if getattr(primary, key) != value:
                variants.append(replace(primary, **{key: value}))
    return Hypothesis(hypothesis_id, description, primary, tuple(variants))
